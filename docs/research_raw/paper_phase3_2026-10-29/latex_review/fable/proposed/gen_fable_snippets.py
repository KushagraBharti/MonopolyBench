ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
def tex(v): return "".join(ESC.get(c, c) for c in str(v))
def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def head(src):
    return f"% Fable proposal (latex_review/fable/proposed). Generated by gen_fable_snippets.py; do not hand-edit values.\n% Source: {src.relative_to(BASE)} sha256 {sha(src)}\n"
def longtable(stem, caption, label, heads, aligns, rows, note, src, size=r"\small"):
    n = len(heads)
    H = " & ".join(r"\textbf{" + h + "}" for h in heads) + r" \\"
    s = [head(src), r"\begingroup" + size + r"\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.1}", "\n",
         r"\begin{longtable}{" + aligns + "}", "\n",
         r"\caption{" + caption + r"}\label{" + label + r"}\\", "\n",
         r"\toprule", "\n", H, "\n", r"\midrule\endfirsthead", "\n",
         r"\multicolumn{" + str(n) + r"}{l}{\tablename\ \thetable\ (continued)}\\", "\n", r"\toprule", "\n", H, "\n", r"\midrule\endhead", "\n",
         r"\midrule\multicolumn{" + str(n) + r"}{r}{Continued on next page}\\\endfoot", "\n", r"\bottomrule\endlastfoot", "\n"]
    for r in rows:
        assert len(r) == n, (stem, r)
        s.append(" & ".join(r) + r" \\" + "\n")
    s += [r"\end{longtable}\endgroup", "\n", r"\tablenote{" + note + "}", "\n"]
    (OUT / f"{stem}.tex").write_text("".join(s))

