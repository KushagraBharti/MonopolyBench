r"""Opus proposal: native LaTeX for the three Opus peer exhibits, generated from their sources.

Usage (repository root):
  python/.venv/bin/python -I <this> <phase3-base> <out.tex>

The script copies the wording from opus/exhibits/{normative_contracts.md, affordance_ledger.md}
and the values from cost_usage.csv; it adds only exhibit names, unit labels and a
cross-reference note. Exhibits use \caption* plus a manual List-of-Tables entry, so they do
not take the shared T-number sequence (T10+ would look like shared exhibits). Requires
booktabs, longtable, array, xurl (for \path) and pdflscape in the host preamble. The
md headings "T6."/"T7." were Opus proposal numbers and are replaced by OC-1/OC-2 because
shared T6/T7 are the elimination and build-recovery tables.
"""
import csv
import hashlib
import re
import sys
from pathlib import Path

from markdown_it import MarkdownIt

base, out = Path(sys.argv[1]), Path(sys.argv[2])
EX = base / "opus/exhibits"
MD = MarkdownIt().enable("table")
ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
       "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
       "–": "--", "—": "---", "’": "'", "“": "``", "”": "''", "…": r"\ldots{}",
       "×": r"\ensuremath{\times}", "§": r"\S{}"}


def tex(s):
    # Straight ASCII double quotes: opening after start/space/bracket, otherwise closing.
    s = re.sub(r'(^|(?<=[\s(\[]))"', "\x01", s).replace('"', "\x02")
    return "".join(ESC.get(c, c) for c in s).replace("\x01", "``").replace("\x02", "''")


def model_id(v):
    return r"\allowbreak".join(r"\texttt{" + tex(x) + ("/" if i < len(v.split("/")) - 1 else "") + "}"
                                for i, x in enumerate(v.split("/")))


def inline(tokens):
    r = []
    for t in tokens:
        if t.type == "text":
            r.append(tex(t.content))
        elif t.type in {"softbreak", "hardbreak"}:
            r.append(" ")
        elif t.type == "strong_open":
            r.append(r"\textbf{")
        elif t.type == "em_open":
            r.append(r"\emph{")
        elif t.type in {"strong_close", "em_close"}:
            r.append("}")
        elif t.type == "code_inline":
            r.append(r"\path{" + t.content + "}" if "{" not in t.content else r"\texttt{" + tex(t.content) + "}")
        else:
            raise ValueError(t.type)
    return "".join(r)


def blocks(md):
    """Yield ('h', level, text) | ('p', text) | ('ul', [items]) | ('table', rows)."""
    toks = MD.parse(md)
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.type == "heading_open":
            yield ("h", int(t.tag[1]), inline(toks[i + 1].children)); i += 3; continue
        if t.type == "paragraph_open":
            yield ("p", inline(toks[i + 1].children)); i += 3; continue
        if t.type == "bullet_list_open":
            items = []
            while toks[i].type != "bullet_list_close":
                if toks[i].type == "inline":
                    items.append(inline(toks[i].children))
                i += 1
            yield ("ul", items); i += 1; continue
        if t.type == "table_open":
            rows, row = [], []
            while toks[i].type != "table_close":
                if toks[i].type == "tr_open":
                    row = []
                elif toks[i].type == "inline":
                    row.append(inline(toks[i].children))
                elif toks[i].type == "tr_close":
                    rows.append(row)
                i += 1
            yield ("table", rows); i += 1; continue
        i += 1


def longtable(rows, widths, name, short, sep="4pt"):
    spec = "".join((r">{\raggedleft\arraybackslash}p{" + w[1:] + "}") if w.startswith("R")
                   else (r">{\raggedright\arraybackslash}p{" + w + "}") for w in widths)
    head = " & ".join(r"\textbf{" + h + "}" for h in rows[0]) + r" \\"
    n = len(widths)
    s = [r"\begingroup\footnotesize\setlength{\tabcolsep}{" + sep + r"}\renewcommand{\arraystretch}{1.15}",
         r"\begin{longtable}{" + spec + "}",
         r"\caption*{\textbf{" + name + "}}" + r"\addcontentsline{lot}{table}{" + short + r"}\\",
         r"\toprule", head, r"\midrule\endfirsthead",
         r"\multicolumn{" + str(n) + r"}{@{}l}{\emph{" + short + r" continued}}\\ \toprule", head, r"\midrule\endhead",
         r"\midrule\multicolumn{" + str(n) + r"}{r@{}}{\emph{Continued on next page}}\\ \endfoot",
         r"\bottomrule\endlastfoot"]
    for r in rows[1:]:
        assert len(r) == n, r
        s.append(" & ".join(r) + r" \\")
    s += [r"\end{longtable}", r"\endgroup"]
    return "\n".join(s)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


parts = [
    "% Opus peer exhibits OC-1..OC-3, generated by latex_review/opus/proposed/make_opus_exhibits.py",
    *(f"% source {p.relative_to(base)} sha256 {sha(p)}" for p in
      (EX / "normative_contracts.md", EX / "affordance_ledger.md", EX / "cost_usage.csv",
       EX / "cost_usage.provenance.json")),
    r"\subsection*{Opus peer exhibits}\addcontentsline{toc}{subsection}{Opus peer exhibits}",
    r"\textit{Identifier note.} OC-1 and OC-2 were numbered T6 and T7 in Opus's phase-3 proposal; "
    r"those numbers are \emph{not} the shared T6 (eliminations) or T7 (build recovery). Inside OC-2, "
    r"R-numbers refer to the reconciled phase-2 claim ledger "
    r"(\path{paper_phase2_2026-10-28/core_review/astra/claims.md}); M1 refers to Opus's "
    r"\path{experiment_decisions.md}; ``T4'' refers to Opus's \path{figure_table_plan.md} build-recovery "
    r"table, whose shared counterpart is T7.",
]

# OC-1 normative contracts
nc = list(blocks((EX / "normative_contracts.md").read_text()))
head = parts[-2:]
del parts[-2:]
parts.append(r"\begin{landscape}")
parts.extend(head)
parts.append(r"\begingroup\small")
for b in nc:
    if b[0] == "h":
        continue
    if b[0] == "table":
        parts.append(longtable(b[1], ["1.45in", "2.85in", "2.3in", "2.3in"],
                               "OC-1. Normative contracts in three close environments",
                               "OC-1\\quad Normative contracts in three close environments (Opus)"))
    elif b[0] == "ul":
        parts.append(r"\begin{itemize}" + "".join(r"\item " + x for x in b[1]) + r"\end{itemize}")
    else:
        parts.append(b[1] + "\n")
parts.append(r"\endgroup")
parts.append(r"\end{landscape}")

# OC-2 affordance ledger (three layer tables)
CORR1 = (r"\footnote{Conversion correction, 29 October 2026: the message is logged publicly on every "
         r"action, but delivery into each recipient's prompt is not guaranteed (20-entry public timeline; "
         r"delivery omissions). A logged utterance is not necessarily delivered (integrated outline, "
         r"Sections 3.3 and 6).}")
CORR2 = (r"\footnote{Scope, as in the integrated outline, Section 6: reset and local branching are tested at "
         r"these stated prefixes; full-prompt equality beyond memory, provider suffixes and general rollout "
         r"termination are not thereby demonstrated.}")
al = list(blocks((EX / "affordance_ledger.md").read_text()))
widths = {5: ["1.95in", "1.95in", "1.45in", "1.6in", "1.85in"], 3: ["2.4in", "3.9in", "2.5in"]}
parts.append(r"\begin{landscape}")
parts.append(r"\textbf{OC-2. Affordance ledger: what the sandbox implements, what this cohort used, "
             r"what remains unimplemented}" + "\n")
layer = ""
for b in al:
    if b[0] == "h":
        if b[1] == 2:
            layer = re.sub(r"^Layer (\d).*", r"\1", b[2])
            parts.append(r"\paragraph*{" + b[2] + "}")
        continue
    if b[0] == "table":
        rows = b[1]
        if len(rows[0]) == 3 and layer == "3":
            w = ["2.45in", "2.75in", "3.6in"]
        else:
            w = widths[len(rows[0])]
        rows = [[c.replace("visible to all players", "visible to all players" + CORR1)
                  .replace("20 branch checks, all passing", "20 branch checks, all passing" + CORR2)
                  for c in r] for r in rows]
        parts.append(longtable(rows, w, f"OC-2, layer {layer}",
                               f"OC-2\\quad Affordance ledger, layer {layer} (Opus)"))
    else:
        parts.append(b[1] + "\n")
parts.append(r"\end{landscape}")

# OC-3 cost and usage
rows = list(csv.DictReader(open(EX / "cost_usage.csv", newline="")))
name = {"Argon": "Gemini (Argon)"}


def grp(v):
    return f"{int(v):,}"


body = [["Agent", "OpenRouter model", "Effort", "Decisions", "Own-model attempts",
         "Attempts missing cost", "Known cost (USD)", "USD / decision", "Prompt tokens",
         "Completion tokens", "Reasoning tokens", "Completion tok. / decision",
         "Reasoning tok. / decision", "Latency s / decision (observational)"]]
for r in rows:
    cost = r["known_cost_usd"]
    body.append([name.get(r["configured_agent"], r["configured_agent"]),
                 model_id(r["openrouter_model_id"]), r["reasoning_effort"],
                 grp(r["decisions"]), grp(r["own_model_attempts"]), grp(r["attempts_missing_cost"]),
                 (r"$\geq$\," if int(r["attempts_missing_cost"]) else "") + f"{float(cost):.2f}", r["known_cost_per_decision_usd"],
                 grp(r["prompt_tokens"]), grp(r["completion_tokens"]), grp(r["reasoning_tokens"]),
                 grp(r["completion_tokens_per_decision"]), grp(r["reasoning_tokens_per_decision"]),
                 r["latency_s_per_decision"]])
total = sum(float(r["known_cost_usd"]) for r in rows)
assert abs(total - 141.71) < 0.005 and sum(int(r["decisions"]) for r in rows) == 6989
parts.append(r"\begin{landscape}")
parts.append(longtable(body, ["0.62in", "1.36in", "0.5in", "R0.5in", "R0.52in", "R0.5in", "R0.56in",
                              "R0.5in", "R0.6in", "R0.6in", "R0.6in", "R0.5in", "R0.5in", "R0.55in"],
                       "OC-3. Provider cost and token usage by configured agent",
                       "OC-3\\quad Provider cost and token usage (Opus)", sep="2.5pt"))
parts.append(
    r"{\footnotesize\textit{Notes.} Money is provider \textbf{USD} as reported by OpenRouter, not game dollars. "
    rf"Known cost totals {total:.2f}~USD. Known cost is a lower bound (marked $\geq$) wherever attempts lack "
    r"accounting: Opus's 1,600 refused attempts and 3 Grok attempts have no OpenRouter cost record, so the "
    r"Opus token totals are lower bounds as well. Decisions sum to 6,989. All four "
    r"agents ran with provider-native reasoning effort ``medium'', which does not equalize compute. Completion "
    r"and reasoning tokens follow provider-specific accounting and are not summed across providers. Latency is "
    r"wall-clock observational metadata and does not affect game progression. Source: \path{opus/exhibits/cost_usage.csv}, "
    r"provenance \path{cost_usage.provenance.json} (20 \path{run/usage.json} files via \path{cohort_overview.json}).\par}")
parts.append(r"\end{landscape}")
out.write_text("\n\n".join(parts) + "\n")
print(out)
