"""Typeset exact, source-qualified transcript excerpts from the retained manifest."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def escape(text: str) -> str:
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
                    "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    # Explicit glyphs avoid TeX's ligature conversion of straight quotation marks.
    replacements['"'] = r"\char34{}"
    return "".join(replacements.get(c, c) for c in text).replace("\n\n", r"\par ").replace("\n", " ")


def render(manifest: dict) -> str:
    lines = ["% Generated by tools/build_transcript_cards.py; do not edit quotation text.",
             "% All quoted spans are in data/transcript_manifest.json. Bracketed ellipses are editorial."]
    for quote in manifest["quotes"]:
        parts = []
        for excerpt in quote["excerpts"]:
            field = manifest["fields"][excerpt["field_id"]]
            assert hashlib.sha256(field["text"].encode()).hexdigest() == field["field_sha256"]
            start, stop = excerpt["span"]
            assert field["text"][start:stop] == excerpt["text"], quote["id"]
            parts.append(escape(excerpt["text"]))
        body = r" \textnormal{[\ldots]} ".join(parts)
        lines.append(r"\DeclareTranscriptQuote{" + quote["id"] + "}{" + escape(quote["metadata"]) + "}{" + body + "}")
    return "\n".join(lines) + "\n"


def main():
    manifest = json.loads((ROOT / "data/transcript_manifest.json").read_text())
    target = ROOT / "sections/transcript_quotes.tex"
    target.write_text(render(manifest))
    print(json.dumps({"quotes": len(manifest["quotes"]), "cases": len(manifest["cases"]),
                      "output": str(target), "sha256": hashlib.sha256(target.read_bytes()).hexdigest()}))


if __name__ == "__main__":
    main()
