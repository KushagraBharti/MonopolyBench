#!/usr/bin/env python3
"""Generate the quotation macros used by ``replacement_prose.tex``.

Each quotation is specified by game, decision, channel and two anchors.  The
script extracts the exact span from the stored field, so no quotation is
retyped by hand.  It writes ``replacement_quotes.tex`` and
``data/quote_manifest.json`` (source file hash, line, field, offsets, span
hash).  Whitespace runs inside a span are rendered as one space in LaTeX; the
manifest keeps the exact stored text.

Stored records only.  No engine, replay or model query.
"""
