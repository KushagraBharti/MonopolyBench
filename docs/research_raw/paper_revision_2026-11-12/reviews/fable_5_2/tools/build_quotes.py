CHANNEL = {
    "note": "applied private note",
    "public": "public message",
    "provider": "provider-returned text",
    "content": "assistant content, not applied",
}

TEX = {
    "\\": r"\textbackslash{}", "$": r"\$", "&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    "<": r"\textless{}", ">": r"\textgreater{}", "—": "---", "–": "--",
    "’": "'", "‘": "`", "“": "``", "”": "''", "→": r"$\rightarrow$",
}


def tex_escape(s: str) -> str:
    s = re.sub(r"\s+", " ", s.strip())
    return "".join(TEX.get(ch, ch) for ch in s)


def field_text(g, k, field):
    rs = g.resolved[k]
    if field == "note":
        return rs["final_action"].get("private_thought")
    if field == "public":
        return rs["final_action"].get("public_message")
    if field == "provider":
        return g.provider_reasoning(k)
    if field == "content":
        sel = g.selected_attempt(k) or rs["attempts"][-1]
        return sel.get("assistant_content")
    raise KeyError(field)


def main():
    games = load_all()
    manifest, lines = [], [
        "% Generated by tools/build_quotes.py from stored decisions.jsonl fields. Do not edit by hand.",
        "% Exact stored spans, offsets and hashes: data/quote_manifest.json.",
    ]
    for qid, gn, k, field, start, end in SPEC:
        g = games[gn]
        text = field_text(g, k, field)
        assert text, (qid, "empty field")
        if start is None:
            a, b = 0, len(text)
            span = text
            # full field, trailing whitespace trimmed for display only
        else:
            a = text.find(start)
            assert a >= 0 and text.count(start) == 1, (qid, "start anchor", text.count(start))
            e = text.find(end, a)
            assert e >= 0, (qid, "end anchor")
            b = e + len(end)
            span = text[a:b]
        st, rs = g.started[k], g.resolved[k]
        cond = (rs.get("sequence_meta") or {}).get("response_condition")
        speaker = g.model[st["player_id"]]
        label = f"{speaker} · {CHANNEL[field]} · G{gn} d{k}"
        if cond and cond != "standard":
            label += " · action-only recovery"
        label += " · full field" if start is None else " · excerpt"
        path = g.run / "decisions.jsonl"
        manifest.append({
            "id": qid, "game": gn, "decision": k, "speaker": speaker, "channel": CHANNEL[field],
            "response_condition": cond, "full_field": start is None,
            "source": str(path.relative_to(path.parents[4])),
            "source_sha256": sha256_file(path),
            "decision_id": rs["decision_id"],
            "start": a, "end": b,
            "field_sha256": hashlib.sha256(text.encode()).hexdigest(),
            "span_sha256": hashlib.sha256(span.encode()).hexdigest(),
            "span": span,
        })
        lines.append(r"\DeclareQuote{%s}{%s}{%s}" % (qid, tex_escape(label).replace("·", r"\,\textperiodcentered\,"), tex_escape(span)))
    (HERE / "replacement_quotes.tex").write_text("\n".join(lines) + "\n")
    (HERE / "data" / "quote_manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    print(len(manifest), "quotations written")
    for m in manifest:
        print(m["id"], "|", re.sub(r"\s+", " ", m["span"])[:150])


if __name__ == "__main__":
    main()
