"""Verify every quoted span against its original record and emit LaTeX macros.

Each registry entry names a game, decision, field and exact text. The script
locates the field in the saved decision record, requires the text to occur
verbatim, records the field hash and character offset, and writes
sections/gen_quotes.tex defining \\Q{id}. A missing span stops the build.
Read-only with respect to records.
"""
from __future__ import annotations

import json
import sys

import lib
from tables import esc


def field_text(q: dict) -> str | None:
    z = lib.decision(q["game"], q["decision"])
    rz = z["decision_resolved"]
    fa = rz["final_action"]
    f = q["field"]
    if f == "note":
        return fa.get("private_thought")
    if f == "public":
        return fa.get("public_message")
    if f in ("provider", "content"):
        atts = rz["attempts"]
        a = atts[q.get("attempt", len(atts) - 1)]
        m = lib.message_of(a) or {}
        return m.get("reasoning") if f == "provider" else m.get("content")
    if f == "carried":
        notes = z["decision_started"]["prompt_payload"]["game_state"]["memory"].get("your_private_thoughts_last_10") or []
        for n in notes:
            if n.get("turn_index") == q["turn"] and q["text"] in n.get("thought", ""):
                return n["thought"]
        return None
    raise ValueError(f)


def main() -> None:
    reg = json.loads((lib.DRAFT / "data/quote_registry.json").read_text())
    out, manifest, bad = [], [], []
    for q in reg:
        t = field_text(q)
        if not t or q["text"] not in t:
            bad.append(q["id"])
            continue
        rz = lib.decision(q["game"], q["decision"])["decision_resolved"]
        manifest.append({**q, "speaker": lib.label(rz["player_name"]), "turn_index": rz["turn_index"],
                         "decision_id": rz["decision_id"], "source_file": lib.rel(lib.decisions_path(q["game"])),
                         "field_sha256": lib.sha256_text(t), "offset": t.index(q["text"]),
                         "full_field": q["text"] == t.strip()})
        out.append(f"\\expandafter\\def\\csname q@{q['id']}\\endcsname{{{esc(q['text'])}}}")
    if bad:
        print("UNVERIFIED QUOTES:", bad)
        sys.exit(1)
    (lib.DRAFT / "sections/gen_quotes.tex").write_text(
        "% Generated by tools/quotes.py from data/quote_registry.json; every span verified verbatim.\n"
        "\\newcommand{\\Q}[1]{\\csname q@#1\\endcsname}\n" + "\n".join(out) + "\n")
    lib.write_json("quote_manifest.json", manifest)
    print(f"{len(manifest)} quotes verified")


if __name__ == "__main__":
    main()
