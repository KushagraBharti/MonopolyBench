"""Generate the two inline excerpts that replacement_prose.tex adds.

Each span must occur exactly once in the applied private note of the named
decision. Writes review_quotes.tex (macros) and data/review_quote_manifest.json
(file, line, field, offsets, hashes). No quotation text is typed by hand in
the replacement prose.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from common import MODEL, REPO, REVIEW, decisions, dump, game_dir  # noqa: E402

SPEC = [
    ("rv-g14-hold", 14, 207, "private_thought", "Cash $602 is the asset."),
    ("rv-g16-hold", 16, 234, "private_thought", "Do not unmortgage, do not mortgage early (10% tax), do not build."),
]


def tex(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("$", "\\$"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#"), ("_", "\\_")):
        s = s.replace(a, b)
    return s


lines = [
    "% Generated by reviews/fable_5_2/tools/build_review_quotes.py from canonical decisions.jsonl.",
    "% Do not edit quotation text. Offsets and hashes: data/review_quote_manifest.json.",
]
manifest = []
for key, g, d, field, span in SPEC:
    res = decisions(g)[d]["resolved"]
    text = res["final_action"][field]
    assert text.count(span) == 1, (key, text.count(span))
    start = text.index(span)
    path = os.path.relpath(os.path.join(game_dir(g), "decisions.jsonl"), REPO)
    manifest.append(
        {
            "key": key,
            "game": g,
            "decision": d,
            "speaker": MODEL[res["openrouter_model_id"]],
            "channel": "applied private note",
            "attempts": len(res["attempts"]),
            "fallback_used": res["fallback_used"],
            "applied_action": res["final_action"]["action"],
            "file": path,
            "line": res["_line"],
            "field": f"/final_action/{field}",
            "start": start,
            "end": start + len(span),
            "span": span,
            "span_sha256": hashlib.sha256(span.encode()).hexdigest(),
            "field_sha256": hashlib.sha256(text.encode()).hexdigest(),
        }
    )
    lines.append(f"\\DeclareInlineQuote{{{key}}}{{{tex(span)}}}")
with open(os.path.join(REVIEW, "review_quotes.tex"), "w") as fh:
    fh.write("\n".join(lines) + "\n")
dump("review_quote_manifest.json", manifest)
print(json.dumps(manifest, indent=1))
