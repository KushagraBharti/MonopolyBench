#!/usr/bin/env python3
"""Generate appendix tables as LaTeX from this draft's re-tabulations (no hand-typed table bodies).

Inputs : data/offer_retabulation.json, data/economy_retabulation.json, data/distress_retabulation.json,
         data/conflict_join.json, ../../data/t01_cohort.json
Output : sections/generated_tables.tex  (one \\newcommand per table body)
"""
import json, pathlib
HERE = pathlib.Path(__file__).resolve().parent.parent
D = HERE / "data"
o = json.loads((D / "offer_retabulation.json").read_text())
e = json.loads((D / "economy_retabulation.json").read_text())
ds = json.loads((D / "distress_retabulation.json").read_text())
cj = json.loads((D / "conflict_join.json").read_text())
coh = json.loads((HERE.parent.parent / "data" / "t01_cohort.json").read_text())
M = ["Sol", "Gemini", "Opus", "Grok"]
CELLS = [("author_only", "Writer only"), ("recipient_only", "Recipient only"), ("both", "Both"), ("neither", "Neither")]
GROUP = {"BROWN": "brown", "LIGHT_BLUE": "light blue", "PINK": "pink", "ORANGE": "orange", "RED": "red", "YELLOW": "yellow", "GREEN": "green", "DARK_BLUE": "dark blue"}
ROUTE = {"trade": "trade", "direct_purchase": "purchase", "auction": "auction", "creditor_inheritance": "estate"}
out = ["% Generated by tools/make_tables.py; do not edit."]
def cmd(name, rows): out.append("\\newcommand{\\%s}{%%\n%s}" % (name, "\n".join(rows)))
def acr(t): return f"{t['n']} & {t['accept']} & {t['counter']} & {t['reject']}"

# cohort
rows = []
fc = {r["game"]: r for r in e["first_completion_rows"]}
for c in coh:
    g = c["game"]; f = fc[g]
    built = "yes" if f["built_first_window"] else "no"
    rows.append(f"{g} & {(g-1)//4+1} & {c['rotation']} & {c['turns']} & {c['winner']} & {c['winner_seat']} & {f['model']} & {GROUP[f['group']]} & {ROUTE[f['route']]} & {f['turn']} & {built} & {'yes' if f['first_completer_won'] else 'no'}\\\\")
cmd("CohortRows", rows)

# cell by recipient
rows = []
for m in M:
    for i, (k, lab) in enumerate(CELLS):
        rows.append(f"{m if i == 0 else ''} & {lab} & {acr(o['cell_by_recipient'][m][k])}\\\\")
    if m != M[-1]: rows.append("\\addlinespace")
cmd("CellByRecipientRows", rows)
rows = []
for b in "12345":
    a, r = o["cell_by_block"][b]["author_only"], o["cell_by_block"][b]["recipient_only"]
    rows.append(f"{b} & {acr(a)} & {acr(r)}\\\\")
cmd("CellByBlockRows", rows)
rows = []
for g in range(1, 21):
    a, r = o["cell_by_game"][str(g)]["author_only"], o["cell_by_game"][str(g)]["recipient_only"]
    rows.append(f"{g} & {acr(a)} & {acr(r)}\\\\")
cmd("CellByGameRows", rows)
rows = []
for k, lab in CELLS:
    rows.append(f"{lab} & {acr(o['cells_first_offer'][k])} & {acr(o['cells_later_offer'][k])}\\\\")
cmd("CellByPositionRows", rows)
rows = []
for k, lab in CELLS:
    t = o["cash_direction"][k]
    rows.append(f"{lab} & {t['n']} & {t['author_pays']} & {t['no_net_cash']} & {t['recipient_pays']} & {int(t['median'])} & {acr(cj['cells_excluding_conflict_responses'][k])}\\\\")
cmd("CellCashRows", rows)
rows = []
for thr in ("50", "100", "150", "200"):
    t = ds["thresholds"][thr]; s = ds["settlement_sensitivity"][thr]
    rows.append(f"\\${thr} & {acr(t['bid_to_cash_poor_recipient'])} & {acr(t['ask_by_cash_poor_writer'])} & {s['cash_poor_seller_settlements']} & {s['of_which_buyer_completes']}\\\\")
cmd("CashPoorRows", rows)

# never legal rows
rows = []
for t in e["never_legal_rows"]:
    reason = "deed arrived mortgaged" if t["interest"] > 0 else "cash below one house"
    paid = f"\\${t['net_cash_paid']}" if t["net_cash_paid"] >= 0 else f"received \\${-t['net_cash_paid']}"
    rows.append(f"G{t['game']} d{t['decision']} & {t['model']} & {GROUP[t['group']]} & {paid} & \\${t['interest']} & \\${t['cash_after']} & \\${t['house_cost']} & {reason}\\\\")
cmd("NeverLegalRows", rows)

# eliminations by game
rows = []
er = e["elimination_rows"]
for g in range(1, 21):
    rr = sorted([r for r in er if r["game"] == g], key=lambda r: r["order"])
    cells = []
    for r in rr:
        cred = "bank" if r["creditor"] == "BANK" else r["creditor"]
        mark = {"upper_bound_impossibility": "", "legal_payment_witness": "$^{p}$", "exhaustive_financing_impossibility": "$^{h}$"}[r["certificate"]]
        cells.append(f"{r['debtor']}$\\to${cred}{mark} & \\${r['owed']:,} & \\${r['full_bound']:,}")
    rows.append(f"{g} & {rr[0]['winner']} & " + " & ".join(cells) + "\\\\")
cmd("EliminationRows", rows)
(HERE / "sections" / "generated_tables.tex").write_text("\n".join(out) + "\n")
print("wrote", len(out) - 1, "table bodies")
