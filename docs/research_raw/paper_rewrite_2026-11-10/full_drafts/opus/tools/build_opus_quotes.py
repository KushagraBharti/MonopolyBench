#!/usr/bin/env python3
"""Generate exact-span quote macros for quotes added in the Opus full draft.

Reads canonical saved-game decisions.jsonl files (read-only), locates the
resolved decision, checks that each excerpt is a contiguous substring of the
applied final_action field, and writes:
  - ../sections/opus_quotes.tex        (\\DeclareTranscriptQuote macros)
  - ../data/opus_quote_manifest.json   (offsets, hashes, line numbers)

Run from any directory:  python3 tools/build_opus_quotes.py
No network, no model calls, no writes outside this draft folder.
"""
import hashlib
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DRAFT = HERE.parent
REPO = DRAFT.parents[4]  # .../MonopolyBench
CAMPAIGN = REPO / "saved_games" / "railway-research-12-games-2026-10-25"
GAMES = {
    2: CAMPAIGN / "game-02-102turns-270aabe8" / "run" / "decisions.jsonl",
    11: CAMPAIGN / "game-11-145turns-2b0fe1ce" / "run" / "decisions.jsonl",
}
MODEL = {
    "openai/gpt-6.1-sol": "Sol",
    "google/gemini-4-argon": "Gemini",
    "anthropic/claude-opus-5.5": "Opus",
    "x-ai/grok-4.7": "Grok",
}
CHANNEL = {"public_message": "public message", "private_thought": "applied private note"}

SPECS = [
    ("g2-d124-price", 2, 124, "public_message",
     "Marvin completes your yellows. $650 buys it; $325 doesn't compensate for handing you that monopoly."),
    ("g2-d124-note", 2, 124, "private_thought",
     "At $325 p4 retains $520, enough for nine yellow houses immediately. $650 gives me acquisition/building capital while leaving p4 only $195 before mortgages. Retain the blocker unless paid a substantial monopoly premium."),
    ("g2-d127-final", 2, 127, "public_message",
     "$450, and that's my final offer."),
    ("g2-d127-ceiling", 2, 127, "private_thought",
     "My ceiling is about $475. If p1 comes back somewhere in $450-475 I'll accept."),
    ("g2-d128-keep", 2, 128, "public_message",
     "I'll keep Marvin. $450 doesn't justify giving you a second monopoly while I still lack one."),
    ("g2-d197-reverse", 2, 197, "public_message",
     "These two finish a monopoly for you, and that's worth more than the railroads. I'll do it if you add $100."),
    ("g2-d198-note", 2, 198, "private_thought",
     "Secure the only available monopoly; $100 premium is worth ending dependence on p2."),
    ("g11-d256-public", 11, 256, "public_message",
     "No. Virginia doesn't complete the pinks — you still have St. Charles. Pennsylvania completes your greens. Not trading it."),
    ("g11-d258-public", 11, 258, "public_message",
     "No. Pennsylvania completes your greens. I'm not handing you that set, with or without the pinks."),
    ("g11-d258-note", 11, 258, "private_thought",
     "St. Charles + Virginia would complete my pinks (I have States), but both pinks are weak vs the kill I already have: PP hotel $1500, BW 4-house $1700. Giving mortgaged PA completes their greens (Pacific+NC+PA) and $250 funds houses."),
]


def sha(b):
    return hashlib.sha256(b).hexdigest()


def tex_escape(s):
    out = []
    for ch in s:
        if ch in "$&%#_{}":
            out.append("\\" + ch)
        elif ch == "\\":
            out.append("\\textbackslash{}")
        elif ch == "~":
            out.append("\\textasciitilde{}")
        elif ch == "^":
            out.append("\\textasciicircum{}")
        else:
            out.append(ch)
    return "".join(out)


def load_resolved(path):
    rows = {}
    for line_no, line in enumerate(path.open(encoding="utf-8"), 1):
        r = json.loads(line)
        if r.get("phase") != "decision_resolved":
            continue
        idx = int(r["decision_id"].rsplit("-", 1)[1])
        rows[idx] = (line_no, r)
    return rows


def main():
    cache = {g: load_resolved(p) for g, p in GAMES.items()}
    file_hash = {g: sha(p.read_bytes()) for g, p in GAMES.items()}
    tex = [
        "% Generated by tools/build_opus_quotes.py from canonical decisions.jsonl files.",
        "% Do not edit quotation text by hand. Offsets and hashes: data/opus_quote_manifest.json.",
    ]
    manifest = {"schema": "opus-quote-manifest-v1", "quotes": []}
    for qid, game, dec, field, excerpt in SPECS:
        line_no, r = cache[game][dec]
        fa = r["final_action"]
        text = fa.get(field)
        if not text or excerpt not in text:
            raise SystemExit(f"{qid}: excerpt not found in final_action.{field}")
        start = text.index(excerpt)
        valid = [i for i, a in enumerate(r["attempts"]) if a.get("outcome") == "valid"]
        attempt = valid[-1] if valid else None
        cond = r["sequence_meta"].get("response_condition")
        speaker = MODEL[r["openrouter_model_id"]]
        meta = f"{speaker} · {CHANNEL[field]} · G{game} d{dec} · attempt {attempt} · " + (
            "full field" if excerpt == text else "excerpt")
        tex.append(f"\\DeclareTranscriptQuote{{{qid}}}{{{meta}}}{{{tex_escape(excerpt)}}}")
        manifest["quotes"].append({
            "id": qid,
            "metadata": meta,
            "source": str(GAMES[game].relative_to(REPO)),
            "source_sha256": file_hash[game],
            "jsonl_line_1based": line_no,
            "json_pointer": f"/final_action/{field}",
            "decision_id": r["decision_id"],
            "actor_player_id": r["player_id"],
            "configuration": speaker,
            "turn_index": r["turn_index"],
            "selected_attempt_index": attempt,
            "response_condition": cond,
            "applied_action": fa["action"],
            "field_sha256": sha(text.encode("utf-8")),
            "span_codepoints": [start, start + len(excerpt)],
            "excerpt": excerpt,
            "full_field": text,
        })
    (DRAFT / "sections").mkdir(exist_ok=True)
    (DRAFT / "data").mkdir(exist_ok=True)
    (DRAFT / "sections" / "opus_quotes.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    (DRAFT / "data" / "opus_quote_manifest.json").write_text(
        json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(SPECS)} quotes")


if __name__ == "__main__":
    main()
