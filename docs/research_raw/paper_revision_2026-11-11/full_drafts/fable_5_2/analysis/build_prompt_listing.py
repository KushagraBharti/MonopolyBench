"""Write the stored system prompt and its recovery diff as LaTeX (exact text, escaped only)."""
from __future__ import annotations

import json
from pathlib import Path

from build_quotes import tex_escape

HERE = Path(__file__).resolve().parents[1]
cond = json.loads((HERE / "data" / "a1_conditions.json").read_text())
sp = cond["system_prompt"]
std = sp["standard_text"].strip("\n")


def block(text: str) -> str:
    out = []
    for line in text.split("\n"):
        if not line.strip():
            out.append("\\par\\smallskip")
        else:
            # keep leading hyphen bullets flush; hang-indent wrapped lines
            out.append("\\noindent\\hangindent=1.2em\\hangafter=1 " + tex_escape(line.rstrip()).replace("*", "{*}") + "\\par")
    return "\n".join(out)


start = std.index("### Messages")
end = std.index("Your role is not to explain rules")
excerpt = std[start:end].strip("\n")
head = "% Generated by analysis/build_prompt_listing.py from the stored system prompt (sha256 " + sp["standard_sha256"] + "). Exact text.\n"
(HERE / "sections" / "prompt_excerpt.tex").write_text(head + block(excerpt) + "\n")
(HERE / "sections" / "prompt_full.tex").write_text(head + block(std) + "\n")
diff = "\n".join(line for line in sp["unified_diff"] if not line.startswith(("---", "+++")))
(HERE / "sections" / "prompt_diff.tex").write_text(
    "% Generated by analysis/build_prompt_listing.py. Unified diff, standard (-) to action-only (+), zero context lines.\n" + block(diff) + "\n"
)
print("prompt chars", len(std), "excerpt chars", len(excerpt), "diff lines", len(diff.split("\n")))

import re

msg = cond["opus_refusals"]["refusal_message"]
parts = re.split(r"(https?://[^\s]*[^\s.,;])", msg)
tex = "".join(("\\url{" + p + "}") if p.startswith("http") else tex_escape(p) for p in parts)
(HERE / "sections" / "refusal_message.tex").write_text(
    "% Generated by analysis/build_prompt_listing.py. Exact provider refusal message (one distinct string in the corpus).\n"
    "% URLs are wrapped in \\url{} so that they can break across lines; the characters are unchanged.\n"
    "\\noindent " + tex + "\\par\n"
)
