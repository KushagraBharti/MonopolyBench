"""Generate appendix TeX (prompt text and tables) from data/*.json.

Writes sections/gen_prompt.tex and sections/gen_tables.tex. Nothing here
reads game records directly; it formats the outputs of the analysis
scripts so the printed numbers cannot drift from them.
"""
from __future__ import annotations

import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path


def r2(x):
    return str(Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))

HERE = Path(__file__).resolve().parents[1]
DATA = HERE / "data"
SEC = HERE / "sections"


def esc(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "$": r"\$", "%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}", "*": r"{*}", "-": r"-{}", '"': r"\char34{}"}
    return "".join(rep.get(c, c) for c in s)


def pct(k, n):
    return f"{100 * k / n:.0f}" if n else "--"


def prompt_tex():
    C = json.loads((DATA / "conditions.json").read_text())
    std = C["standard_system_prompt"].strip("\n").splitlines()
    out = [r"% Generated by tools/build_tables.py from data/conditions.json; do not edit.",
           r"\begin{tcolorbox}[colback=transcriptbg,colframe=transcriptborder,boxrule=0.4pt,arc=1.5mm,left=6pt,right=6pt,top=5pt,bottom=5pt,fontupper=\ttfamily\scriptsize\raggedright]"]
    for line in std:
        if line.strip() == "":
            out.append(r"\par\smallskip")
        else:
            out.append(esc(line.rstrip()) + r"\par")
    out.append(r"\end{tcolorbox}")
    diff = [l for l in C["system_prompt_diff"] if l[:1] in "+-" and not l.startswith(("+++", "---"))]
    out.append(r"\noindent Lines removed from and added to the system prompt in the action-only recovery request:")
    out.append(r"\begin{tcolorbox}[colback=white,colframe=transcriptborder,boxrule=0.4pt,arc=1.5mm,left=6pt,right=6pt,top=5pt,bottom=5pt,fontupper=\ttfamily\scriptsize\raggedright]")
    for l in diff:
        if l[1:].strip() == "":
            continue
        out.append((r"\textsf{\textbf{removed}}\quad " if l[0] == "-" else r"\textsf{\textbf{added}}\quad ") + esc(l[1:].strip()) + r"\par")
    out.append(r"\end{tcolorbox}")
    (SEC / "gen_prompt.tex").write_text("\n".join(out) + "\n")


def tables_tex():
    B = json.loads((DATA / "bargaining.json").read_text())
    X = json.loads((DATA / "extras.json").read_text())
    S = json.loads((DATA / "sensitivity.json").read_text())
    C = json.loads((DATA / "conditions.json").read_text())
    Dt = json.loads((DATA / "debt_episodes.json").read_text())
    F = json.loads((DATA / "first_estates.json").read_text())
    out = [r"% Generated by tools/build_tables.py from data/*.json; do not edit."]

    # joint recipient x stage x cell
    rows = []
    cells = ["Author only", "Recipient only", "Both", "Neither"]
    for m in ["Sol", "Gemini", "Opus", "Grok"]:
        for st in ["opening", "later"]:
            parts = []
            for c in cells:
                d = B["joint"][f"{m}|{st}|{c}"]
                parts.append(f"{d['n']} & {d['accept_trade']}/{d['counter_trade']}/{d['reject_trade']}")
            rows.append(f"{m} & {st} & " + " & ".join(parts) + r"\\")
    out.append(r"\newcommand{\JointRows}{" + "\n".join(rows) + "}")

    # opening contrast sensitivity
    rows = []
    def orow(label, d):
        a, n = d["author_only"], d["neither"]
        return f"{label} & {a[0]}/{a[1]} ({pct(*a)}\\%) & {n[0]}/{n[1]} ({pct(*n)}\\%) & {d['diff_pp']:+.1f}\\\\"
    OR = B["open_reject"]
    rows.append(orow("All offers", OR["pooled"]))
    for b in range(1, 6):
        rows.append(orow(f"Seed block {b} only", OR[f"block={b}"]))
    for b in range(1, 6):
        rows.append(orow(f"Without block {b}", OR[f"without_block={b}"]))
    for m in ["Sol", "Gemini", "Grok", "Opus"]:
        rows.append(orow(f"Recipient {m}", OR[f"recipient={m}"]))
    SS = S["open_reject_sensitivity"]
    rows.append(orow("Without Grok conflict-opened threads", SS["without_grok_conflict_threads"]))
    rows.append(orow("Without Opus as author or recipient", SS["without_opus_as_author_or_recipient"]))
    rows.append(orow("Games 1--4 (partial refusal regime)", SS["games_1_4"]))
    rows.append(orow("Games 5--20 (full refusal regime)", SS["games_5_20"]))
    out.append(r"\newcommand{\OpenRows}{" + "\n".join(rows) + "}")

    # concessions by recipient and block
    rows = []
    CC = B["concessions"]
    for m in ["Sol", "Gemini", "Opus", "Grok"]:
        a, n = CC[f"Author only|recipient={m}"], CC[f"Neither|recipient={m}"]
        rows.append(f"Recipient {m} & {a['accept']}/{a['n']} & {n['accept']}/{n['n']}\\\\")
    for b in range(1, 6):
        a, n = CC[f"Author only|block={b}"], CC[f"Neither|block={b}"]
        rows.append(f"Seed block {b} & {a['accept']}/{a['n']} & {n['accept']}/{n['n']}\\\\")
    out.append(r"\newcommand{\ConcessionRows}{" + "\n".join(rows) + "}")

    # price medians
    rows = []
    PR = B["prices"]
    def prow(label, key):
        d = PR[key]
        c, o = d["completing"], d["other"]
        fmt = lambda x: "--" if x[1] is None else f"{r2(x[1])} ({x[0]})"
        return f"{label} & {fmt(c)} & {fmt(o)}"
    for kind, lab in (("ask", "Asks"), ("bid", "Bids")):
        for who in ["All", "Standard authors", "Sol", "Gemini", "Grok", "Opus"]:
            rows.append(prow(f"{lab}, " + {"All": "all authors", "Standard authors": "standard-condition authors"}.get(who, who), f"{kind}|{who}") + r"\\")
        for b in range(1, 6):
            rows.append(prow(f"{lab}, seed block {b}", f"{kind}|block={b}") + r"\\")
        rows.append(r"\midrule")
    for who in ["Sol", "Grok", "Opus"]:
        for mort in (False, True):
            rows.append(prow(f"Asks, {who}, {'mortgaged' if mort else 'unmortgaged'}", f"ask|{who}|mortgaged={mort}") + r"\\")
    out.append(r"\newcommand{\PriceRows}{" + "\n".join(rows) + "}")

    # same-deed pairs
    rows = []
    for p in X["same_deed_pairs"]:
        deed = ", ".join(d.replace("_", " ").title() for d in p["deeds"])
        comp = "; ".join(f"{c['cash']} (t{c['turn']}{', m' if c['mortgaged'] else ''})" for c in p["completing"])
        oth = "; ".join(f"{c['cash']} (t{c['turn']}{', m' if c['mortgaged'] else ''})" for c in p["other"])
        rows.append(f"G{p['game']} & {p['seller_model']} & {esc(deed)} & {comp} & {oth} & {p['first_ask_direction']}\\\\")
    out.append(r"\newcommand{\PairRows}{" + "\n".join(rows) + "}")

    # capacity and standing
    rows = []
    for band in ["full layer", "one house", "less than one house"]:
        o = X["capacity_author_only"].get(f"{band}|opening", {"n": 0})
        l = X["capacity_author_only"].get(f"{band}|later", {"n": 0})
        rows.append(f"{band.capitalize()} & {o.get('reject_trade', 0)}/{o['n']} & {l.get('reject_trade', 0)}/{l['n']}\\\\")
    out.append(r"\newcommand{\CapacityRows}{" + "\n".join(rows) + "}")
    rows = []
    for who in ["author leads", "recipient leads", "third player leads"]:
        o, l = X["standing"][f"{who}|opening"], X["standing"][f"{who}|later"]
        rows.append(f"{who.capitalize()} & {o.get('reject_trade', 0)}/{o['n']} & {l.get('reject_trade', 0)}/{l['n']}\\\\")
    out.append(r"\newcommand{\StandingRows}{" + "\n".join(rows) + "}")

    # refusal chronology
    rows = []
    for g in range(1, 5):
        d = C["per_game"][str(g)]
        t = d["last_accepted_first_attempt_utc"][11:19]
        rows.append(f"G{g} & {d['refused']}/{d['opus_first_attempts']} & {d['share']:.2f} & {t}\\\\")
    k = sum(C["per_game"][str(g)]["refused"] for g in range(5, 21))
    n = sum(C["per_game"][str(g)]["opus_first_attempts"] for g in range(5, 21))
    rows.append(f"G5--G20 & {k}/{n} & 1.00 & none\\\\")
    out.append(r"\newcommand{\RefusalRows}{" + "\n".join(rows) + "}")
    rows = []
    for b, (r_, n_) in C["g1_4_ten_minute_bins_utc"].items():
        rows.append(f"{b} & {r_}/{n_}")
    half = (len(rows) + 1) // 2
    pair_rows = []
    for i in range(half):
        left = rows[i]
        right = rows[i + half] if i + half < len(rows) else "&"
        pair_rows.append(f"{left} & {right}\\\\")
    out.append(r"\newcommand{\BinRows}{" + "\n".join(pair_rows) + "}")
    rows = []
    for m in ["Sol", "Gemini", "Opus", "Grok"]:
        t = C["reasoning_tokens"][m]
        ct = C["completion_tokens"][m]
        up = C["cost_usd"]["upstream_inference_cost_sum"][m]
        uc = C["cost_usd"]["usage_cost_sum"][m]
        br = C["cost_usd"]["byok_aware_rule"][m]
        rows.append(f"{m} & {t['records_with_field']:,} & {t['zero']:,} & {t['mean']:.0f} & {t['max']:,} & {ct['max']:,} & {uc:.2f} & {up:.2f} & {br:.2f}\\\\")
    tot = C["cost_usd"]["totals"]
    rows.append(r"\midrule " + f"All & & & & & & {tot['usage_cost']:.2f} & {tot['upstream']:.2f} & {tot['byok_aware']:.2f}\\\\")
    out.append(r"\newcommand{\TokenRows}{" + "\n".join(rows) + "}")

    # debt summary by model
    E = Dt["episodes"]
    rows = []
    for m in ["Sol", "Gemini", "Opus", "Grok"]:
        xs = [e for e in E if e["model"] == m]
        paid = [e for e in xs if e["outcome"] == "paid"]
        el = [e for e in xs if e["outcome"] == "eliminated"]
        rows.append(f"{m} & {len(xs)} & {len(paid)} & {sum(e['n_decisions'] >= 2 for e in paid)} & {sum('sell_houses_or_hotel' in e['actions'] for e in paid)} & {len(el)}\\\\")
    paid = [e for e in E if e["outcome"] == "paid"]
    el = [e for e in E if e["outcome"] == "eliminated"]
    rows.append(r"\midrule " + f"All & {len(E)} & {len(paid)} & {sum(e['n_decisions'] >= 2 for e in paid)} & {sum('sell_houses_or_hotel' in e['actions'] for e in paid)} & {len(el)}\\\\")
    out.append(r"\newcommand{\DebtRows}{" + "\n".join(rows) + "}")

    # first-estate full table
    rows = []
    for r in F["rows"]:
        st = r["standing"]
        def val(pid):
            for k, v in st.items():
                if k.endswith("/" + pid):
                    return v
        cv = val(r["creditor"])
        lv = val(r["asset_leader"])
        rows.append(f"G{r['game']} & {r['turn']} & {r['debtor_model']} & {r['creditor_model']} & {r['creditor_rank_assets']} & {r['creditor_rank_rent']} & {cv['asset_value']:,} & {r['asset_leader_model']} & {lv['asset_value']:,} & {r['winner_model']}\\\\")
    out.append(r"\newcommand{\EstateRows}{" + "\n".join(rows) + "}")

    # cohort
    rows = []
    for c in S["cohort"]:
        rows.append(f"G{c['game']} & {c['block']} & {c['seed']} & {' / '.join(c['seat_models'])} & {c['turns']} & {c['winner']} & {c['winner_seat']}\\\\")
    out.append(r"\newcommand{\CohortRows}{" + "\n".join(rows) + "}")
    (SEC / "gen_tables.tex").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    prompt_tex()
    tables_tex()
    print("wrote", SEC / "gen_prompt.tex", SEC / "gen_tables.tex")
