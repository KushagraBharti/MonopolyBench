"""Generate new quote definitions from original decision records.

Each quote is a complete applied field (public message or private note) of a
resolved decision. Output: sections/new_quotes.tex (LaTeX definitions; do not
edit by hand) and data/new_quote_manifest.json (path, line, pointer, hashes).
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import corpus

HERE = Path(__file__).resolve().parents[1]
G2 = "saved_games/railway-research-12-games-2026-10-25/game-02-102turns-270aabe8/run/decisions.jsonl"
QUOTES = [
    ("g2-d119-public", G2, 119, "/final_action/public_message", "Sol", "public message"),
    ("g2-d119-note", G2, 119, "/final_action/private_thought", "Sol", "applied private note"),
    ("g2-d120-public", G2, 120, "/final_action/public_message", "Grok", "public message"),
    ("g2-d121-public", G2, 121, "/final_action/public_message", "Sol", "public message"),
]


def tex(s: str) -> str:
    out = []
    for ch in s:
        out.append({"$": r"\$", "%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                    "~": r"\textasciitilde{}", "^": r"\^{}", "\\": r"\textbackslash{}", '"': r"\char34{}"}.get(ch, ch))
    return "".join(out)


def main():
    manifest = []
    lines_tex = ["% Generated by tools/build_new_quotes.py from canonical decisions.jsonl; do not edit quotation text.",
                 "% Paths, line numbers, JSON pointers and hashes: data/new_quote_manifest.json."]
    for qid, rel, idx, pointer, speaker, channel in QUOTES:
        path = corpus.REPO / rel
        raw = path.read_bytes()
        found = None
        for n, line in enumerate(raw.splitlines(), 1):
            obj = json.loads(line)
            if obj["phase"] == "decision_resolved" and obj["decision_id"].endswith(f"-dec-{idx:06d}"):
                found = (n, obj)
                break
        n, obj = found
        node = obj
        for k in pointer.lstrip("/").split("/"):
            node = node[k]
        field = node
        attempt = len(obj["attempts"]) - 1
        cond = obj["attempts"][-1]["response_condition"]
        meta = f"{speaker} · {channel} · G2 d{idx} · attempt {attempt} · full field"
        manifest.append({"id": qid, "metadata": meta, "source": rel, "source_sha256": hashlib.sha256(raw).hexdigest(),
                         "jsonl_line_1based": n, "json_pointer": pointer, "decision_id": obj["decision_id"],
                         "selected_attempt_index": attempt, "response_condition": cond,
                         "applied_action": obj["final_action"]["action"],
                         "field_sha256": hashlib.sha256(field.encode()).hexdigest(), "span_codepoints": [0, len(field)],
                         "excerpt": field})
        lines_tex.append(rf"\DeclareTranscriptQuote{{{qid}}}{{{meta}}}{{{tex(field)}}}")
    (HERE / "sections" / "new_quotes.tex").write_text("\n".join(lines_tex) + "\n")
    (HERE / "data" / "new_quote_manifest.json").write_text(json.dumps({"schema": "opus-new-quotes-v1", "quotes": manifest}, indent=1, ensure_ascii=False))
    print(json.dumps(manifest, indent=1, ensure_ascii=False)[:1500])


if __name__ == "__main__":
    main()
