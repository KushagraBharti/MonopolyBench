"""Generate replacement_quotes.tex from verified manifests (Fable quote manifest; Opus manifest for G2 d119).
Each card re-reads the canonical decisions.jsonl line, checks file and field hashes, and prints only exact spans.
Run from repo root: python3 -I docs/research_raw/paper_revision_2026-11-11/reviews/opus/tools/build_quotes.py"""
import hashlib, json, pathlib, sys
ROOT = pathlib.Path.cwd(); REV = ROOT / "docs/research_raw/paper_revision_2026-11-11"
IDS = ["g15-d169-refusal-note", "g15-d174-sweetener", "g15-d175-final-refusal", "g15-d176-wait-note",
       "g2-d124-price", "g2-d128-note", "g7-d42-final", "g7-d42-ceiling", "g7-d141-timed-bid", "g7-d142-ask-note",
       "g1-d306-offer", "g1-d309-accept-note", "g13-d250-insurance", "g13-d252-floor", "g13-d252-omission",
       "g20-d96-appeal", "g20-d101-refusal", "g12-d249-note", "g12-d249-public", "g18-d420-note", "g18-d431-assurance",
       "g18-d442-withdrawal", "g18-d442-explanation", "g19-d135-public", "g19-d136-public", "g17-d234-public"]
fable = {q["id"]: q for q in json.loads((REV / "full_drafts/fable_5_2/data/quote_manifest.json").read_text())["quotes"]}
opus = json.loads((REV / "full_drafts/opus/data/new_quote_manifest.json").read_text())
opus = opus if isinstance(opus, list) else (opus.get("quotes") or list(opus.values()))
opus = {q["id"]: q for q in opus if isinstance(q, dict) and "id" in q}
def esc(s):
    rep = {"\\": r"\textbackslash{}", "$": r"\$", "%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "—": "---", "–": "--", "’": "'", "‘": "`", "“": "``", "”": "''", "…": r"\ldots{}", "→": r"$\rightarrow$", "≥": r"$\geq$", "≤": r"$\leq$", ">": r"\textgreater{}", "<": r"\textless{}"}
    return "".join(rep.get(c, c) for c in s)
def field(src, line, pointer):
    b = (ROOT / src).read_bytes(); rec = json.loads(b.decode().splitlines()[line - 1]); v = rec
    for part in pointer.strip("/").split("/"):
        v = v[int(part)] if isinstance(v, list) else v[part]
    return hashlib.sha256(b).hexdigest(), v
out, log = [r"% Generated by tools/build_quotes.py from verified manifests. Do not edit."], []
def emit(qid, meta, text):
    out.append(r"\expandafter\def\csname q@" + qid + r"\endcsname{\QuoteCard{" + esc(meta) + "}{" + text + "}}")
for qid in IDS:
    q = fable[qid]; fh, val = field(q["source"], q["jsonl_line_1based"], q["json_pointer"])
    ok = fh == q["source_sha256"] and hashlib.sha256(val.encode()).hexdigest() == q["field_sha256"] and all(val[s["span"][0]:s["span"][1]] == s["text"] for s in q["spans"])
    log.append((qid, ok)); emit(qid, q["metadata"], r" [\ldots] ".join(esc(s["text"]) for s in q["spans"]))
q = opus["g2-d119-note"]; fh, val = field(q["source"], q["jsonl_line_1based"], q["json_pointer"])
a, b = q["span_codepoints"]; ok = fh == q["source_sha256"] and hashlib.sha256(val.encode()).hexdigest() == q["field_sha256"] and val[a:b] == q["excerpt"]
log.append(("g2-d119-note", ok)); emit("g2-d119-note", q["metadata"], esc(val[a:b]))
if not all(ok for _, ok in log):
    print("FAIL", [i for i, ok in log if not ok]); sys.exit(1)
(REV / "reviews/opus/replacement_quotes.tex").write_text("\n".join(out) + "\n")
print("ok", len(log))
