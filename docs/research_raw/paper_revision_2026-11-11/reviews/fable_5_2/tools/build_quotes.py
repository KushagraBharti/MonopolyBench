"""Generate the quotation cards used in replacement_prose.tex from canonical
decisions.jsonl. No quotation is typed by hand.

For each card: read the decision_resolved line, resolve the JSON pointer, take
the full field, and write (a) a TeX definition and (b) a manifest row with the
source hash, 1-based JSONL line, pointer, code-point span and field hash. The
script also asserts the state facts stated around the incident from the saved
prompts and events (event reduction only; no engine import, no replay).
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
REPO = ROOT.parents[2]
OUT_TEX = HERE.parent / "replacement_quotes.tex"
OUT_MAN = HERE.parent / "data/new_quote_manifest.json"
OUT_FACTS = HERE.parent / "data/g20_payment_facts.json"

RUN = "saved_games/railway-research-8-games-2026-10-26/game-20-115turns-fbd1c1b9/run"
import glob
cands = glob.glob(str(REPO / "saved_games/railway-research-*/game-20-*/run"))
assert len(cands) == 1
RUN = str(Path(cands[0]).relative_to(REPO))
SRC = REPO / RUN / "decisions.jsonl"
SRC_SHA = hashlib.sha256(SRC.read_bytes()).hexdigest()

CARDS = [
    # id, zero-based decision, speaker, channel label, pointer
    ("g20-d325-creditor-note", 325, "Gemini", "applied private note", "/final_action/private_thought"),
    ("g20-d327-plan", 327, "Sol", "applied private note", "/final_action/private_thought"),
    ("g20-d329-midway", 329, "Sol", "applied private note", "/final_action/private_thought"),
    ("g20-d336-last", 336, "Sol", "applied private note", "/final_action/private_thought"),
]
LABEL = {"gpt-6.1-sol": "Sol", "gemini-4-argon": "Gemini", "claude-opus-5.5": "Opus", "grok-4.7": "Grok"}

lines = SRC.read_text(encoding="utf-8").split("\n")
started, resolved_line, order = {}, {}, []
for i, ln in enumerate(lines, start=1):
    if not ln.strip():
        continue
    d = json.loads(ln)
    if d["phase"] == "decision_started":
        started[d["decision_id"]] = d
        order.append(d["decision_id"])
    else:
        resolved_line[d["decision_id"]] = (i, d)


def tex(s):
    rep = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "%": r"\%", "&": r"\&", "#": r"\#",
           "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(ch, ch) for ch in s)


man, out = [], ["% Generated by tools/build_quotes.py from canonical decisions.jsonl; do not edit quotation text.",
                "% Paths, lines, JSON pointers, spans and hashes are in data/new_quote_manifest.json."]
for qid, k, speaker, channel, ptr in CARDS:
    did = order[k]
    n, rec = resolved_line[did]
    assert LABEL[rec["player_name"]] == speaker, (qid, rec["player_name"])
    obj = rec
    for part in ptr.strip("/").split("/"):
        obj = obj[part]
    assert isinstance(obj, str) and obj
    attempts = rec["attempts"]
    assert len(attempts) == 1 and str(rec["fallback_used"]) == "False" and str(rec["retry_used"]) == "False", qid
    meta = f"{speaker} · {channel} · G20 d{k} · attempt 0 · full field"
    out.append("\\DeclareTranscriptQuote{%s}{%s}{%s}" % (qid, tex(meta), tex(obj)))
    man.append({"id": qid, "metadata": meta, "game": 20, "decision": k, "decision_id": did,
                "turn": int(rec["turn_index"]), "speaker": speaker, "channel": channel,
                "selected_attempt": 0, "response_condition": "standard", "applied_action": rec["final_action"]["action"],
                "source": f"{RUN}/decisions.jsonl", "source_sha256": SRC_SHA, "jsonl_line_1based": n,
                "json_pointer": ptr, "field_sha256": hashlib.sha256(obj.encode("utf-8")).hexdigest(),
                "full_field": True, "span_codepoints": [0, len(obj)], "text": obj,
                "delivered_to": None, "delivery_note": "private note; not delivered to any other player"})
OUT_TEX.write_text("\n".join(out) + "\n", encoding="utf-8")
OUT_MAN.write_text(json.dumps({"schema": "reviews/fable_5_2 new quotes v1", "quotes": man}, indent=1, ensure_ascii=False), encoding="utf-8")

# ---- state facts asserted around the incident -------------------------------
ev = [json.loads(l) for l in open(REPO / RUN / "events.jsonl")]
def S(k):
    return started[order[k]]
def R(k):
    return resolved_line[order[k]][1]
facts = {}
g325 = S(325)["prompt_payload"]["game_state"]
assert LABEL[S(325)["player_name"]] == "Gemini" and g325["you"]["cash"] == 413
sol = [o for o in g325["others"] if LABEL.get(o["name"]) == "Sol"][0]
own = sol["holdings"]["owned"]
facts["sol_cash_in_gemini_d325_prompt"] = sol["cash"]
facts["sol_houses"] = sum(o["houses"] for o in own)
facts["sol_hotels"] = sum(bool(o["hotel"]) for o in own)
facts["sol_unmortgaged_deeds"] = sum(not o["mortgaged"] for o in own)
facts["sol_deeds"] = len(own)
facts["players_not_bankrupt_at_d325"] = 1 + sum(not o.get("bankrupt") for o in g325["others"])
assert R(325)["final_action"]["action"] == "build_houses_or_hotel"
assert S(326)["prompt_payload"]["game_state"]["you"]["cash"] == 213
liq = list(range(327, 337))
assert all(S(k)["decision_type"] == "LIQUIDATION_DECISION" and LABEL[S(k)["player_name"]] == "Sol" for k in liq)
facts["sol_cash_at_each_liquidation_prompt"] = [S(k)["prompt_payload"]["game_state"]["you"]["cash"] for k in liq]
facts["owed"] = S(327)["prompt_payload"]["action_state"]["scenario"]["owed_amount"]
facts["actions"] = [R(k)["final_action"]["action"] for k in liq]
facts["sol_cash_after_payment"] = S(337)["prompt_payload"]["game_state"]["you"]["cash"]
t108 = [e for e in ev if e["turn_index"] == 108]
facts["sale_cash_events"] = [e["payload"]["delta"] for e in t108 if e["type"] == "CASH_CHANGED" and e["payload"].get("reason") == "SELL_BUILDING"]
facts["mortgage_cash_events"] = [e["payload"]["delta"] for e in t108 if e["type"] == "CASH_CHANGED" and e["payload"].get("reason") == "MORTGAGE"]
rent = [e for e in t108 if e["type"] == "RENT_PAID"]
facts["rent_paid_event"] = {"seq": rent[0]["seq"], "amount": rent[0]["payload"]["amount"], "space_index": rent[0]["payload"]["space_index"]}
facts["hotel_built_event_turn_107"] = [e["seq"] for e in ev if e["turn_index"] == 107 and e["type"] == "HOTEL_BUILT" and e["payload"]["space_index"] == 34]
facts["bankruptcy_turns"] = sorted({e["turn_index"] for e in ev if e["type"] == "CASH_CHANGED" and e["payload"].get("reason") == "BANKRUPTCY"})
facts["game_end"] = [(e["turn_index"], e["payload"]) for e in ev if e["type"] == "GAME_ENDED"][0]
assert facts["owed"] == 1400 and facts["sol_cash_at_each_liquidation_prompt"][0] == 49
assert sum(facts["sale_cash_events"]) == 700 and sum(facts["mortgage_cash_events"]) == 665
assert facts["sol_cash_after_payment"] == 14 and 49 + 700 + 665 - 1400 == 14
assert facts["actions"].count("sell_houses_or_hotel") == 2 and facts["actions"].count("mortgage_property") == 8
assert facts["rent_paid_event"]["amount"] == 1400 and facts["rent_paid_event"]["space_index"] == 34
assert facts["sol_houses"] == 9 and facts["sol_hotels"] == 2 and facts["sol_unmortgaged_deeds"] == 8
facts["source_sha256"] = {f"{RUN}/decisions.jsonl": SRC_SHA,
                          f"{RUN}/events.jsonl": hashlib.sha256((REPO / RUN / "events.jsonl").read_bytes()).hexdigest()}
OUT_FACTS.write_text(json.dumps(facts, indent=1))
print("cards", len(man))
for m in man:
    print(m["id"], "line", m["jsonl_line_1based"], len(m["text"]), "chars")
print(json.dumps({k: v for k, v in facts.items() if k != "source_sha256"}))
